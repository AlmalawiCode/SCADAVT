"""Run a networked experiment that includes controlled attacks.

Extends the plain networked runner (``scadavt.experiments.networked``): it
generates the deployment, injects one isolated attacker container per attack,
and opens/closes each attack window at its simulated time by toggling the
attacker's control file — exactly as the base runner opens network-fault
windows. Every attack action is recorded with its wall-clock and simulated time
in ``faults.csv``, which is the label source for the dataset.

    python -m scadavt.attacks.runner experiments/a1_fdi_t2.yaml

The experiment file is a normal networked experiment with an extra ``attacks``
list:

    name: a1_fdi_t2
    deployment: {profile: full, seed: 1, hours: 24, step: 1800, tick: 0.5, period: "0.5"}
    attacks:
      - {id: a1, kind: fdi, target: PLC1, tag: T2_LVL, mode: freeze,
         start_h: 8, end_h: 14}
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import yaml

from .. import scenario as sc
from ..deploy import compose as dc
from ..experiments import networked
from . import catalog
from . import deploy as adeploy


def airgap_networks(doc: dict, keep: str = "back") -> dict:
    """Mark every lab network except ``keep`` as Docker-internal.

    Air-gaps the SCADA plane so no node (the attacker included) can egress to
    the Internet through a router's host NAT, while the back channel stays
    reachable from the host for sim-clock following and ground-truth collection.
    """
    for name, net in doc.get("networks", {}).items():
        if name == keep:
            continue
        if not isinstance(net, dict):
            net = doc["networks"][name] = {}
        net["internal"] = True
    return doc


class AttackRunner(networked.Runner):
    def __init__(self, exp: dict, build: Path, out: Path):
        super().__init__(exp, build, out)
        scen_path = exp.get("deployment", {}).get("scenario") or sc.DEFAULT_SCENARIO
        self.scen = sc.load(scen_path)
        self.plan = dc.plan(self.scen)
        self.attacks = [catalog.Attack.from_spec(d, i)
                        for i, d in enumerate(exp.get("attacks", []))]
        # validate every attack up front (fail fast, before starting containers)
        for atk in self.attacks:
            catalog.resolve(atk, self.scen, self.plan)

    @property
    def _adir(self) -> Path:
        return self.build / "logs" / "attacks"

    def generate(self):
        super().generate()
        if not self.attacks:
            return
        cf = self.build / "docker-compose.yml"
        doc = yaml.safe_load(cf.read_text())
        logs_vol = f"{self.build.resolve() / 'logs'}:/logs"
        image = doc["services"]["wds"]["image"]
        doc["services"].update(
            adeploy.attacker_services(self.scen, self.plan, self.attacks, image, logs_vol))
        airgap_networks(doc)
        cf.write_text("# Generated by scadavt.deploy.compose, attackers added by "
                      "scadavt.attacks.runner.\n"
                      + yaml.dump(doc, Dumper=dc._NoAliasDumper, sort_keys=False, width=120))
        self._adir.mkdir(parents=True, exist_ok=True)
        for atk in self.attacks:
            (self._adir / f"{atk.id}.json").write_text('{"active": false}')
        # schedule attack windows alongside the network-fault windows
        faults = self.exp.setdefault("faults", [])
        for atk in self.attacks:
            faults.append({"start_h": atk.start_h, "end_h": atk.end_h,
                           "kind": "_attack", "target": atk.id, "_atk": atk})

    def apply(self, f: dict, phase: str, sim_h: float):
        if f.get("kind") != "_attack":
            return super().apply(f, phase, sim_h)
        atk: catalog.Attack = f["_atk"]
        active = phase == "start"
        (self._adir / f"{atk.id}.json").write_text(json.dumps({"active": active}))
        self.actions.append({"wall_time": round(time.time(), 3), "sim_h": round(sim_h, 4),
                             "phase": phase, "kind": atk.kind,
                             "target": f"{atk.plc}.{atk.tag}",
                             "output": f"mode={atk.mode} value={atk.value}"})
        print(f"[{sim_h:7.2f} h] {phase:5s} {atk.kind} {atk.plc}.{atk.tag}")

    def collect(self):
        summary = super().collect()
        # carry the attacker action logs into the result bundle
        if self._adir.exists():
            dst = self.out / "attacks"
            dst.mkdir(parents=True, exist_ok=True)
            for f in self._adir.glob("*"):
                if f.is_file():
                    (dst / f.name).write_bytes(f.read_bytes())
        summary["attacks"] = [vars(a) for a in self.attacks]
        return summary


def main(argv=None):
    import asyncio

    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("experiment", type=Path)
    ap.add_argument("--build", type=Path)
    ap.add_argument("--out", type=Path)
    ap.add_argument("--keep", action="store_true")
    a = ap.parse_args(argv)
    exp = yaml.safe_load(a.experiment.read_text())
    name = exp.get("name", a.experiment.stem)
    root = networked.ROOT
    r = AttackRunner(exp, a.build or root / "build" / name,
                     a.out or root / "results" / "attacks" / name)
    r.down()
    r.generate()
    t0 = time.time()
    r.up()
    try:
        asyncio.run(r.follow())
    finally:
        time.sleep(3)
        if not a.keep:
            r.down()
    s = r.collect()
    s["runner_wall_seconds"] = round(time.time() - t0, 1)
    print(json.dumps({k: s.get(k) for k in ("name", "sim_hours", "metrics")},
                     indent=1, default=str)[:1500])


if __name__ == "__main__":
    main()
